#!/usr/bin/env node
/**
 * Réécrit le fichier d'index du client généré (ng-openapi-gen) en réexportations « étoile ».
 *
 * ng-openapi-gen écrit des réexportations nommées (`export { x as x } from './fn/…'`). Avec
 * elles, esbuild range toute fonction d'API utilisée, même par une seule page chargée à la
 * demande, dans le bundle **initial** de l'application qui importe l'index (vérifié au lot
 * L3, étape L3.3 : +7,6 kB pour le portail). Avec `export * from …`, chaque fonction suit
 * les pages qui l'utilisent, comme les composants de la bibliothèque partagée.
 *
 * Le contenu exporté est le même (les types sont effacés à la compilation) ; un nom exporté
 * par deux modules ferait échouer la compilation (TS2308), jamais silencieusement.
 * Appelé par `npm run api:generate`, après la génération : le client n'est pas édité à la main.
 *
 * Usage : node scripts/api-barrel.mjs <index.ts>
 */
import { readFile, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

const HEADER = '/* eslint-disable */\n/* Code generated by ng-openapi-gen DO NOT EDIT. */\n';
const REEXPORT = /^export\s+(?:type\s+)?(?:\{[^}]*\}|\*)\s+from\s+'([^']+)';$/;

export function starBarrel(source) {
  const modules = [];
  for (const raw of source.split('\n')) {
    const line = raw.trim();
    if (!line || line.startsWith('/*') || line.startsWith('//')) {
      continue;
    }
    const match = REEXPORT.exec(line);
    if (!match) {
      throw new Error(`Index du client : ligne inattendue « ${line} »`);
    }
    if (!modules.includes(match[1])) {
      modules.push(match[1]);
    }
  }
  if (!modules.length) {
    throw new Error('Index du client : aucune réexportation');
  }
  const body = modules.map((module) => `export * from '${module}';`).join('\n');
  return `${HEADER}// Réexportations « étoile » (scripts/api-barrel.mjs) : bundle initial minimal.\n\n${body}\n`;
}

async function main([file]) {
  if (!file) {
    throw new Error('Usage : node scripts/api-barrel.mjs <index.ts>');
  }
  await writeFile(file, starBarrel(await readFile(file, 'utf8')));
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  main(process.argv.slice(2)).catch((error) => {
    console.error(error.message);
    process.exit(1);
  });
}
